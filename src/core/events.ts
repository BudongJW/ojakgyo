/**
 * The unified event model. Every platform connector translates its own
 * payloads into these shapes, so rules and outputs never need to know
 * which platform an event came from.
 */

export const PLATFORMS = ['chzzk', 'soop', 'cime', 'mock'] as const;
export type Platform = (typeof PLATFORMS)[number];

export const ROLES = ['streamer', 'manager', 'chat_manager', 'viewer'] as const;
export type Role = (typeof ROLES)[number];

export const EVENT_TYPES = ['chat', 'donation', 'subscription'] as const;
export type EventType = (typeof EVENT_TYPES)[number];

export interface Viewer {
  /** Platform-specific user/channel id, when the platform exposes it. */
  id?: string;
  nickname: string;
  role: Role;
}

interface BaseEvent {
  /** Unique id generated by ojakgyo. */
  id: string;
  platform: Platform;
  /** The streamer's channel the event belongs to. */
  channelId: string;
  /** Epoch milliseconds when ojakgyo received the event. */
  receivedAt: number;
}

export interface ChatEvent extends BaseEvent {
  type: 'chat';
  user: Viewer;
  message: string;
  /** Emoji token -> image URL. */
  emojis: Record<string, string>;
}

export type DonationKind = 'chat' | 'video' | 'balloon' | 'other';

export interface DonationEvent extends BaseEvent {
  type: 'donation';
  /** `null` for anonymous donations. */
  user: Viewer | null;
  /** Normalised amount in KRW. */
  amount: number;
  currency: 'KRW';
  kind: DonationKind;
  message: string;
  emojis: Record<string, string>;
}

export interface SubscriptionEvent extends BaseEvent {
  type: 'subscription';
  user: Viewer;
  tier: number;
  tierName?: string;
  months: number;
  message: string;
}

export type OjakgyoEvent = ChatEvent | DonationEvent | SubscriptionEvent;

let counter = 0;

/** Short, sortable, process-unique id. */
export function newEventId(): string {
  counter = (counter + 1) % 1_000_000;
  return `${Date.now().toString(36)}-${counter.toString(36).padStart(4, '0')}`;
}

/** Display name for the person behind an event. */
export function actorName(event: OjakgyoEvent, anonymousName = '익명의 후원자'): string {
  return event.user?.nickname ?? anonymousName;
}
